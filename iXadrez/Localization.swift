/// Portuguese algebraic notation uses the local piece initials: Rei, Dama, Torre, Bispo, Cavalo.
func sanText(_ san: String, _ lang: AppLanguage) -> String {
    guard lang == .pt else { return san }
    let map: [Character: Character] = ["K": "R", "Q": "D", "R": "T", "N": "C"]
    return String(san.map { map[$0] ?? $0 })
}

final class Loc: ObservableObject {
    static let shared = Loc()

    @Published var language: AppLanguage {
        didSet { UserDefaults.standard.set(language.rawValue, forKey: "xadrez-lang") }
    }

    private init() {
        let saved = UserDefaults.standard.string(forKey: "xadrez-lang")
        self.language = AppLanguage(rawValue: saved ?? "pt") ?? .pt
    }

    func toggle() {
        language = language == .pt ? .en : .pt
    }

    func t(_ key: String) -> String {
        strings[language]?[key] ?? strings[.pt]?[key] ?? key
    }
}
